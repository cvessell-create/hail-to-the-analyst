// Turns the framework loop-model report (vessell/loop_models.py latest.json) into
// declared tuning for the next generated level. Rule: aim the new level at a
// 0.6 clear rate. Enemy count scales with the latest mission's clear rate, fuel
// with timeout rate (navigation trouble) and health with death rate.
'use strict';
const path = require('node:path'), crypto = require('node:crypto');
const { confinedPath, readFile, writeFile } = require('./repository-paths');

const TARGET_CLEAR = 0.6;
const clamp = (v, lo, hi) => Math.max(lo, Math.min(hi, v));

function tune(report, source) {
  const cond = report.probability.p_outcome_given_mission;
  const missions = Object.keys(cond).map(Number).sort((a, b) => a - b);
  const last = cond[String(missions[missions.length - 1])];
  const mean = k => missions.reduce((s, m) => s + (cond[String(m)][k] || 0), 0) / missions.length;
  const clear = last.complete || 0, timeout = mean('timeout'), death = mean('dead');
  return {
    schema: 'hail-level-tuning/v1',
    source,
    rule: 'enemies=round(14*clear/0.6) in [8,22]; fuel=2+round(10*timeout) in [2,6]; health=2+round(12*death) in [2,6]',
    inputs: { latestMission: missions[missions.length - 1], clear, meanTimeout: timeout, meanDeath: death,
      dominantStrategy: report.backward_induction && report.backward_induction.dominant_strategy || null },
    enemies: clamp(Math.round(14 * clear / TARGET_CLEAR), 8, 22),
    fuelCaches: clamp(2 + Math.round(10 * timeout), 2, 6),
    healthKits: clamp(2 + Math.round(12 * death), 2, 6),
    evidence: 'design tuning from recorded autopilot episodes; not a claim about human players'
  };
}

function main(argv) {
  const input = argv[2];
  if (!input || argv.length > 4) throw Error('usage: node scripts/build-level-tuning.js <repository-report.json> [repository-out.js]');
  const root = path.resolve(__dirname, '..');
  const filename = confinedPath(root, path.resolve(input));
  const out = confinedPath(root, argv[3] ? path.resolve(argv[3]) : 'engine/level-tuning.js');
  const raw = readFile(root, filename);
  const tuning = tune(JSON.parse(raw), { file: path.relative(root, filename).split(path.sep).join('/'),
    sha256: crypto.createHash('sha256').update(raw).digest('hex') });
  writeFile(root, out, '// Generated by scripts/build-level-tuning.js. Do not edit by hand.\n' +
    '// SPDX-License-Identifier: GPL-2.0-or-later\n' +
    '(function(root,t){if(typeof module===\'object\'&&module.exports)module.exports=t;else root.HailLevelTuning=t;})' +
    '(typeof globalThis!==\'undefined\'?globalThis:this,' + JSON.stringify(tuning, null, 2) + ');\n');
  return tuning;
}

if (require.main === module) console.log(JSON.stringify(main(process.argv), null, 2));
module.exports = { tune };
